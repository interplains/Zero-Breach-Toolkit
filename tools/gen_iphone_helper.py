"""Embed requirements-iphone-backup.txt into scan/zbtriage/iphonehelper_reqs.py.

The Linux "make an iPhone backup for me" helper installs pymobiledevice3 (GPL-3.0) into its own folder
with every file pinned by SHA-256. The pinned list lives in requirements-iphone-backup.txt (made with
pip-compile --generate-hashes); this copies it into a Python constant so the single-file program
carries it too. Run after changing the requirements file; a test checks the two match.
"""
import hashlib
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "requirements-iphone-backup.txt")
OUT = os.path.join(ROOT, "scan", "zbtriage", "iphonehelper_reqs.py")


def main():
    with open(SRC, "r", encoding="utf-8") as fh:
        text = fh.read().replace("\r\n", "\n")
    if '"""' in text or "\\" in text.replace(" \\\n", ""):
        raise SystemExit("unexpected characters in the requirements file")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    body = ('"""Generated by tools/gen_iphone_helper.py from requirements-iphone-backup.txt. Do not edit."""\n'
            "IH_REQUIREMENTS_SHA256 = \"{}\"\n"
            "IH_REQUIREMENTS = (\n".format(digest))
    for line in text.splitlines(keepends=True):
        body += "    {!r}\n".format(line)
    body += ")\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print("wrote", OUT, digest)


if __name__ == "__main__":
    main()
