"""Build scan/zbtriage/ouidata.py: which company each network hardware-address prefix belongs to.

Source: the IEEE Registration Authority's public MA-L assignments, https://standards-oui.ieee.org/oui/oui.csv
(download it and pass its path). Only the prefix and a shortened company name are kept - no addresses. Stored
lzma-compressed and base85-encoded, like the translations, so the program stays one file and works offline.

    python tools/gen_ouidata.py path/to/oui.csv
"""
import base64
import csv
import datetime
import io
import lzma
import os
import re
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scan", "zbtriage", "ouidata.py")
_SUFFIX = re.compile(r"[,.]?\s+(?:co\.?,?\s*ltd|co\.|ltd|limited|inc|incorporated|corp|corporation|llc|gmbh|ag|s\.?a\.?|"
                     r"b\.?v\.?|plc|pte|pty|srl|s\.r\.l|oy|ab|as|kg|technologies|technology|electronics|"
                     r"communications?|international|holdings?)\.?$", re.I)


def short_name(name: str) -> str:
    name = re.sub(r"\s+", " ", name).strip().strip('"')
    for _ in range(4):
        shorter = _SUFFIX.sub("", name).strip(" ,.")
        if shorter == name or len(shorter) < 3:
            break
        name = shorter
    return name[:48]


def main(path: str) -> None:
    rows = {}
    with open(path, encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            if row.get("Registry") != "MA-L":
                continue
            prefix = (row.get("Assignment") or "").strip().upper()
            if re.fullmatch(r"[0-9A-F]{6}", prefix):
                rows[prefix] = short_name(row.get("Organization Name") or "")
    text = "\n".join("{}\t{}".format(p, rows[p]) for p in sorted(rows)).encode("utf-8")
    blob = base64.b85encode(lzma.compress(text, preset=9 | lzma.PRESET_EXTREME)).decode("ascii")
    lines = [blob[i:i + 116] for i in range(0, len(blob), 116)]
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Generated by tools/gen_ouidata.py from the IEEE public MA-L assignments ({} prefixes, {}).\n'
                 'Do not edit by hand."""\n\nOUI_COUNT = {}\nOUI_BLOB = (\n'.format(
                     len(rows), datetime.date.today().isoformat(), len(rows)))
        for line in lines:
            fh.write("    '{}'\n".format(line))
        fh.write(")\n")
    print("wrote {} ({:,} prefixes, {:,} bytes)".format(OUT, len(rows), os.path.getsize(OUT)))


if __name__ == "__main__":
    main(sys.argv[1])
