"""Generate scan/zbtriage/orddata.py: ordinal-to-name tables for ws2_32 / wsock32 / oleaut32, so the toolkit's
imphash matches pefile's (the reference everyone's imphash values come from).

Source: pefile's ordlookup package (MIT licence, Copyright (c) 2004-2024 Ero Carrera). Usage:
    python tools/gen_ordlookup.py PATH_TO_PEFILE_ORDLOOKUP_FOLDER
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "scan", "zbtriage", "orddata.py")


def table(path):
    tree = ast.parse(open(path, encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "ord_names":
            value = ast.literal_eval(node.value)
            return {int(k): (v.decode("ascii") if isinstance(v, bytes) else str(v)) for k, v in value.items()}
    raise SystemExit("no ord_names in " + path)


def main(folder):
    tables = {name: table(os.path.join(folder, name + ".py")) for name in ("oleaut32", "ws2_32", "wsock32")}
    lines = ['"""Ordinal-to-name tables for ws2_32, wsock32 and oleaut32 (imphash compatibility with pefile).',
             "", "Generated by tools/gen_ordlookup.py from pefile's ordlookup package.",
             "pefile: MIT licence, Copyright (c) 2004-2024 Ero Carrera. See NOTICE.", '"""', "", "ORD_NAMES = {"]
    for name, mapping in tables.items():
        lines.append("    {!r}: {{".format(name))
        for k in sorted(mapping):
            lines.append("        {}: {!r},".format(k, mapping[k]))
        lines.append("    },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT, {k: len(v) for k, v in tables.items()})


if __name__ == "__main__":
    main(sys.argv[1])
