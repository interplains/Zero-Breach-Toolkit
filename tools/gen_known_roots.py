"""Generate scan/zbtriage/trustdata.py: the root certificates the major trust programs carry.

    python tools/gen_known_roots.py MICROSOFT_CSV MOZILLA_CSV

Inputs are the public CCADB reports:
  Microsoft: https://ccadb.my.salesforce-sites.com/microsoft/IncludedCACertificateReportForMSFTCSV
  Mozilla:   https://ccadb.my.salesforce-sites.com/mozilla/IncludedCACertificateReportCSVFormat
Every Microsoft entry is kept whatever its status (a "Disabled" root can still sit in an older store),
so a certificate missing from this file is one no major program distributes.

Output: a Python module with two sets of fingerprints (SHA-1 and SHA-256) and the as-of date, so the
source, the single-file build and the programs all carry it without data files. The certificates are
public facts (fingerprints); the module states its sources and date.
"""
import csv
import datetime
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "scan", "zbtriage", "trustdata.py")

# Windows ships roots of its own that are not CCADB-listed public CAs: Microsoft's code-signing,
# timestamping and product roots, and the Xbox Live IPsec roots that Windows gaming components install.
# Matched by exact SHA-1 thumbprint (the subject text proves nothing). Thumbprints read from a
# Windows 11 installation's LocalMachine\Root store (2026-11-08) plus the long-standing legacy roots.
WINDOWS_BUILTIN = {
    "8F43288AD272F3103B6FB1428485EA3014C0BCFE": "Microsoft Root Certificate Authority 2011",
    "3B1EFD3A66EA28B16697394703A72CA340A05BD5": "Microsoft Root Certificate Authority 2010",
    "CDD4EEAE6000AC7F40C3802C171E30148030C072": "Microsoft Root Certificate Authority",
    "A43489159A520F0D93D032CCAF37E7FE20A8B419": "Microsoft Root Authority",
    "7F88CD7223F3C813818C994614A89C99FA3B5247": "Microsoft Authenticode(tm) Root Authority",
    "245C97DF7514E7CF2DF8BE72AE957B9E04741E85": "Microsoft Time Stamping Service Root (1997)",
    "18F7C1FCC3090203FD5BAA2F861A754976C8DD25": "NO LIABILITY ACCEPTED, (c)97 VeriSign, Inc.",
    "0119E81BE9A14CD8E22F40AC118C687ECBA3F4D8": "Microsoft Time Stamp Root Certificate Authority 2014",
    "31F9FC8BA3805986B721EA7295C65B3A44534274": "Microsoft ECC TS Root Certificate Authority 2018",
    "06F1AA330B927B753A40E68CDF22E34BCBEF3352": "Microsoft ECC Product Root Certificate Authority 2018",
    "F8DB7E1C16F1FFD4AAAD4AAD8DFF0F2445184AEB": "Microsoft Development Root Certificate Authority 2014",
    "EBE112F56D5FE0BA23289319C89D7784A10CEB61": "XBL Client IPsec Issuing CA",
    "645984515AB9FB7AE8065B9DDB0E908F8E870ED5": "XBL Server IPsec Issuing CA",
}


def clean(value):
    return (value or "").strip().replace("\t", " ").upper().replace(":", "")


def main(msft, mozilla):
    sha1, sha256 = set(WINDOWS_BUILTIN), set()
    with open(msft, encoding="utf-8-sig", newline="") as fh:
        for row in csv.DictReader(fh):
            a, b = clean(row.get("SHA-1 Fingerprint")), clean(row.get("SHA-256 Fingerprint"))
            if len(a) == 40:
                sha1.add(a)
            if len(b) == 64:
                sha256.add(b)
    with open(mozilla, encoding="utf-8-sig", newline="") as fh:
        for row in csv.DictReader(fh):
            b = clean(row.get("SHA-256 Fingerprint"))
            if len(b) == 64:
                sha256.add(b)
    if len(sha1) < 300 or len(sha256) < 300:
        sys.exit("only {} / {} roots read; the reports look truncated".format(len(sha1), len(sha256)))
    lines = ['"""Root certificates distributed by the major trust programs (public facts: fingerprints).',
             "",
             "Generated by tools/gen_known_roots.py from the CCADB public reports (Microsoft Trusted Root Program,",
             "all statuses, and Mozilla) plus Windows' own built-in roots. Used only to recognise ordinary roots;",
             'a root NOT listed here is reported as worth a look. Do not edit by hand.',
             '"""',
             "TRUST_AS_OF = {!r}".format(datetime.date.today().isoformat()),
             "TRUST_SHA1 = frozenset(("]
    lines += ["    {!r},".format(v) for v in sorted(sha1)]
    lines += ["))", "TRUST_SHA256 = frozenset(("]
    lines += ["    {!r},".format(v) for v in sorted(sha256)]
    lines += ["))", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT, len(sha1), "SHA-1 and", len(sha256), "SHA-256 fingerprints")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
