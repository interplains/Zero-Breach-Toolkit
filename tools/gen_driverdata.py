"""Generate scan/zbtriage/driverdata.py: fingerprints of Windows drivers known to be vulnerable or malicious.

Source: LOLDrivers (https://github.com/magicsword-io/LOLDrivers), Apache License 2.0, its compiled
loldrivers.io/content/api/drivers.json at a pinned commit. Usage:

    python tools/gen_driverdata.py PATH_TO_drivers.json COMMIT

Only entries LOLDrivers marks Verified are used, and only their file fingerprints (SHA-256, or SHA-1 where a
sample has no SHA-256) and first file name. Never download or clone the LOLDrivers repository itself: its
drivers/ folder holds the actual driver files, which antivirus rightly flags.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "scan", "zbtriage", "driverdata.py")
_HEX = {64: re.compile(r"^[0-9a-f]{64}$"), 40: re.compile(r"^[0-9a-f]{40}$")}


def main(path, commit):
    data = json.load(open(path, encoding="utf-8"))
    sha256, sha1 = {}, {}
    skipped = 0
    for entry in data:
        if str(entry.get("Verified")).lower() != "true":
            skipped += 1
            continue
        cat = {"vulnerable driver": "v", "malicious": "m"}.get(str(entry.get("Category")).lower())
        if not cat:
            skipped += 1
            continue
        tags = [t for t in (entry.get("Tags") or []) if isinstance(t, str) and t.lower().endswith(".sys")]
        name = re.sub(r"[^A-Za-z0-9_.\-]", "", tags[0])[:64] if tags else "driver.sys"
        for sample in entry.get("KnownVulnerableSamples") or []:
            h256 = str(sample.get("SHA256") or "").strip().lower()
            h1 = str(sample.get("SHA1") or "").strip().lower()
            if _HEX[64].match(h256):
                # a sample listed as both: malicious wins
                if sha256.get(h256, ("", ""))[0] != "m":
                    sha256[h256] = (cat, name)
            elif _HEX[40].match(h1):
                if sha1.get(h1, ("", ""))[0] != "m":
                    sha1[h1] = (cat, name)
    lines = ['"""Windows drivers known to be vulnerable (v) or malicious (m): file fingerprint -> (kind, file name).',
             "", "Generated by tools/gen_driverdata.py from LOLDrivers (https://github.com/magicsword-io/LOLDrivers),",
             "commit " + commit + ", loldrivers.io/content/api/drivers.json; Verified entries only.",
             "LOLDrivers: Apache License 2.0; see NOTICE and third_party/loldrivers/LICENSE.", '"""', "",
             "DRIVER_SHA256 = {"]
    lines += ["    {!r}: {!r},".format(h, v) for h, v in sorted(sha256.items())]
    lines += ["}", "", "DRIVER_SHA1 = {"]
    lines += ["    {!r}: {!r},".format(h, v) for h, v in sorted(sha1.items())]
    lines += ["}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    kinds = {}
    for v in list(sha256.values()) + list(sha1.values()):
        kinds[v[0]] = kinds.get(v[0], 0) + 1
    print("wrote {}: {} SHA-256 + {} SHA-1 fingerprints ({}), {} entries skipped (unverified or other)".format(
        OUT, len(sha256), len(sha1), kinds, skipped))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
