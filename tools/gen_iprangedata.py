"""Build scan/zbtriage/iprangedata.py: which big company runs an internet address, from their own published lists.

Sources (download them into one folder and pass its path):
  goog.json   https://www.gstatic.com/ipranges/goog.json          Google (all of Google's own address space)
  gcloud.json https://www.gstatic.com/ipranges/cloud.json         Google Cloud (rented by customers)
  cf4.txt / cf6.txt  https://www.cloudflare.com/ips-v4 / ips-v6  Cloudflare
  ms365.json  https://endpoints.office.com/endpoints/worldwide    Microsoft 365
  msft.json, meta.json, akamai.json, apple.json, amazon16509.json, amazon14618.json
              https://stat.ripe.net/data/announced-prefixes/data.json?resource=AS<n>  (the registry's routing data
              for each company's own network: Microsoft AS8075, Meta AS32934, Akamai AS20940, Apple AS714,
              Amazon AS16509 / AS14618)
  telegram.txt https://core.telegram.org/resources/cidr.txt         Telegram
Only address ranges and a company name are kept. Stored lzma-compressed and base85-encoded, like the other data.

    python tools/gen_iprangedata.py path/to/folder
"""
import base64
import datetime
import io
import ipaddress
import json
import lzma
import os
import sys

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scan", "zbtriage", "iprangedata.py")
OWNERS = [
    ("gcloud", "Google Cloud - a server rented from Google by a company or a person"),
    ("google", "Google"),
    ("cloudflare", "Cloudflare - it carries the traffic of many websites and apps"),
    ("m365", "Microsoft 365 (Outlook, Teams, OneDrive)"),
    ("microsoft", "Microsoft"),
    ("meta", "Meta (Facebook, Instagram, WhatsApp)"),
    ("akamai", "Akamai - it delivers content for many websites and apps"),
    ("apple", "Apple"),
    ("amazon", "Amazon Web Services - often a server rented by a company or a person"),
    ("telegram", "Telegram"),
]


def _ripe(path):
    return [p["prefix"] for p in json.load(open(path, encoding="utf-8"))["data"]["prefixes"]]


def main(folder):
    j = lambda name: os.path.join(folder, name)   # noqa: E731
    ranges = {key: set() for key, _ in OWNERS}
    for p in json.load(open(j("gcloud.json")))["prefixes"]:
        ranges["gcloud"].add(p.get("ipv4Prefix") or p.get("ipv6Prefix"))
    for p in json.load(open(j("goog.json")))["prefixes"]:
        ranges["google"].add(p.get("ipv4Prefix") or p.get("ipv6Prefix"))
    for name in ("cf4.txt", "cf6.txt"):
        ranges["cloudflare"] |= {line.strip() for line in open(j(name)) if line.strip()}
    for item in json.load(open(j("ms365.json"))):
        ranges["m365"] |= set(item.get("ips") or [])
    ranges["microsoft"] |= set(_ripe(j("msft.json")))
    ranges["meta"] |= set(_ripe(j("meta.json")))
    ranges["akamai"] |= set(_ripe(j("akamai.json")))
    ranges["apple"] |= set(_ripe(j("apple.json"))) | {"17.0.0.0/8"}
    ranges["amazon"] |= set(_ripe(j("amazon16509.json"))) | set(_ripe(j("amazon14618.json")))
    ranges["telegram"] |= {line.strip() for line in open(j("telegram.txt")) if line.strip()}
    lines, total = [], 0
    for code, (key, _label) in enumerate(OWNERS):
        for prefix in sorted(ranges[key]):
            try:
                net = ipaddress.ip_network(prefix, strict=False)
            except ValueError:
                continue
            if net.prefixlen < 8:
                continue
            lines.append("{}\t{}".format(net.with_prefixlen, code))
            total += 1
    text = ("\n".join(lines)).encode("ascii")
    blob = base64.b85encode(lzma.compress(text, preset=9 | lzma.PRESET_EXTREME)).decode("ascii")
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Generated by tools/gen_iprangedata.py from the companies\' own published address lists and the\n'
                 'registry\'s routing data ({} ranges, {}). Do not edit by hand."""\n\n'.format(
                     total, datetime.date.today().isoformat()))
        fh.write("IPR_OWNERS = {!r}\n".format([label for _key, label in OWNERS]))
        fh.write("IPR_BLOB = (\n")
        for i in range(0, len(blob), 116):
            fh.write("    '{}'\n".format(blob[i:i + 116]))
        fh.write(")\n")
    print("wrote {} ({:,} ranges, {:,} bytes)".format(OUT, total, os.path.getsize(OUT)))


if __name__ == "__main__":
    main(sys.argv[1])
