"""Build scan/zbtriage/extensiondata.py from chrome-mal-ids' current-list-meta.csv.

Source: https://github.com/mallorybowes/chrome-mal-ids (data/current-list-meta.csv), licence CC BY 4.0,
Copyright (c) 2021-2026 Mallory Bowes Brown and contributors. Only confirmed entries are kept
(CONFIRM-MAL >= 1: researcher and/or Google confirmed); "under investigation" (0) is left out.

usage: python tools/gen_extension_list.py path/to/current-list-meta.csv [expected-sha256]
"""
import csv
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "scan", "zbtriage", "extensiondata.py")


def main(path, expected=None):
    raw = open(path, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    if expected and digest != expected:
        raise SystemExit("checksum mismatch: " + digest)
    rows = list(csv.DictReader(raw.decode("utf-8-sig").splitlines()))
    out = {}
    for row in rows:
        ext_id = (row.get("EXTID") or "").strip()
        if not re.fullmatch(r"[a-p]{32}", ext_id):
            continue
        try:
            level = int((row.get("CONFIRM-MAL") or "0").strip() or 0)
        except ValueError:
            continue
        if level < 1:
            continue
        # Names are not shipped: the check reads each extension's real name from the computer, and the
        # list's names include product names our publishing rules keep out of the repository.
        name = ""
        threat = re.sub(r"[^\w ,/-]", "", (row.get("THREAT-TYPE") or "").strip())[:40]
        threat = "malicious" if not threat or threat.upper() == "UNKNOWN" else threat.replace(",", ", ")
        who = {1: "researcher-confirmed", 2: "Google-confirmed", 3: "researcher- and Google-confirmed"}.get(level, "")
        out[ext_id] = "{}{} ({})".format(name + ": " if name else "", threat, who)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write('"""Malicious browser extension IDs (Chrome / Edge), confirmed entries only.\n\n'
                 "Generated by tools/gen_extension_list.py - do not edit.\n"
                 "Source: chrome-mal-ids, https://github.com/mallorybowes/chrome-mal-ids\n"
                 "Licence: CC BY 4.0 - Copyright (c) 2021-2026 Mallory Bowes Brown and contributors.\n"
                 "Source file sha256: {}; {} rows read, {} confirmed kept.\n"
                 '"""\n'.format(digest, len(rows), len(out)))
        fh.write("BAD_EXTENSIONS_SOURCE_SHA256 = {!r}\n".format(digest))
        fh.write("BAD_EXTENSIONS = {\n")
        for ext_id in sorted(out):
            fh.write("    {!r}: {!r},\n".format(ext_id, out[ext_id]))
        fh.write("}\n")
    print("kept", len(out), "of", len(rows), "->", OUT)


if __name__ == "__main__":
    main(*sys.argv[1:])
