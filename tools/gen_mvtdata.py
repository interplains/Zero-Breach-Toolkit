"""Generate scan/zbtriage/mvtdata.py: built-in copies of the indicator files hosted in mvt-project/mvt-indicators.

That repository is MIT-licensed (Copyright (c) 2022 MVT), so its own files can travel with the program: someone
who never runs --update, or cannot (offline, blocked), still has these lists from the first scan. Each built-in
copy is the exact file this release pins (feeds.FEED_PINS / FEED_FILE_SHA256): the generator refuses any file
whose SHA-256 differs, and the scan checks it again before use. Files the index only points to in other
repositories (Amnesty International, Citizen Lab) carry no licence file and stay download-only.

Stored zlib-compressed and base64-encoded: smaller, and antivirus does not read a list of spyware addresses
inside the program as if the program were the spyware.

    python tools/gen_mvtdata.py
"""
import base64
import datetime
import hashlib
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "scan"))
OUT = os.path.join(HERE, "..", "scan", "zbtriage", "mvtdata.py")
REPO = "mvt-project/mvt-indicators"


def main():
    from zbtriage import feeds
    pin = feeds.FEED_PINS[REPO]
    rows = []
    for src in feeds.SOURCES:
        if src["repo"] != REPO:
            continue
        url = feeds.RAW + REPO + "/" + pin + "/" + src["path"]
        data = feeds._fetch(url)
        digest = hashlib.sha256(data).hexdigest()
        if digest != feeds.FEED_FILE_SHA256.get(src["id"]):
            raise SystemExit("{}: the file at the pinned commit does not match the release's SHA-256".format(src["id"]))
        packed = base64.b64encode(zlib.compress(data, 9)).decode("ascii")
        rows.append((src["id"], digest, packed, len(data)))
        print("  {:<32} {:>8} bytes -> {:>7} stored".format(src["id"], len(data), len(packed)))
    lines = ['"""Built-in copies of the indicator files hosted in mvt-project/mvt-indicators, used when no downloaded',
             "copy exists. Generated by tools/gen_mvtdata.py at commit " + pin + ".",
             "mvt-indicators: MIT License, Copyright (c) 2022 MVT; see NOTICE and third_party/mvt-indicators/LICENSE.",
             "Each value: (SHA-256 of the original file, base64 of the zlib-compressed file).", '"""', "",
             "MVT_BUILTIN_COMMIT = {!r}".format(pin),
             "# When these copies were generated from the reviewed pins: their age is counted from here, so the",
             "# report asks for --update once they are old, exactly as for a downloaded copy.",
             "MVT_BUILTIN_DATE = {!r}".format(datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")),
             "", "MVT_BUILTIN = {"]
    for sid, digest, packed, _size in rows:
        lines.append("    {!r}: ({!r},".format(sid, digest))
        for i in range(0, len(packed), 100):
            lines.append("        {!r}".format(packed[i:i + 100]))
        lines.append("    ),")
    lines += ["}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote {}: {} files, {:,} bytes".format(OUT, len(rows), os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
