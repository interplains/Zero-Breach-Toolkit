"""Hand-curated indicator files and the Citizen Lab MISP exports.

Curated files hold values a person read out of a report. The rules: every row
names a documented source and a family, the file carries an as-of date, the
values pass the same validation as everything else, and the file can be
regenerated byte for byte from its generator (so review happens on the script).
"""

from __future__ import annotations

import io
import os
import re
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from zbtriage import feeds  # noqa: E402
from zbtriage.iocs import TYPE_DOMAIN, TYPE_IP, TYPE_SHA256, load  # noqa: E402

CURATED = os.path.join(REPO, "iocs", "curated_mercenary.txt")
GENERATOR = os.path.join(REPO, "tools", "gen_curated_mercenary.py")


class TestCuratedMercenary(unittest.TestCase):
    def setUp(self):
        self.text = io.open(CURATED, encoding="utf-8").read()
        self.set = load(CURATED)

    def test_every_row_is_cited_and_has_a_family(self):
        documented = set(re.findall(r"^#\s{3}([a-z][a-z0-9-]+)\s{2}", self.text, re.M))
        self.assertTrue(documented)
        for ind in self.set.indicators:
            with self.subTest(indicator=ind.value):
                self.assertIn(ind.source, documented)
                self.assertTrue(ind.family)

    def test_has_an_as_of_date(self):
        self.assertRegex(self.set.asof or "", r"^\d{4}-\d{2}-\d{2}$")

    def test_key_paragon_server_is_present_and_graded_as_decaying_ip(self):
        ind = self.set.lookup("46.183.184.91")
        self.assertIsNotNone(ind)
        self.assertEqual((ind.type, ind.tier, ind.family),
                         (TYPE_IP, "infrastructure-ip", "Paragon Graphite"))

    def test_invalid_certificate_name_was_left_out(self):
        self.assertIsNone(self.set.lookup("forti.external-sht_prd_2.com"))

    def test_generator_reproduces_the_file_exactly(self):
        out = os.path.join(tempfile.mkdtemp(prefix="gen_"), "x.txt")
        subprocess.run([sys.executable, "-I", GENERATOR, out], check=True,
                       capture_output=True)
        self.assertEqual(io.open(out, encoding="utf-8").read(), self.text)


class TestMispCsv(unittest.TestCase):
    def test_misp_types_map_to_kinds_and_urls_give_their_host(self):
        path = os.path.join(tempfile.mkdtemp(prefix="misp_"), "iocs.misp.csv")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("uuid,event_id,category,type,value,comment,to_ids,date\n"
                     'a,1,Network activity,domain,"lure.example","",1,20160824\n'
                     'b,1,Network activity,ip-dst,"5.6.7.8","",1,20160824\n'
                     'c,1,Network activity,url,"https://time-local.example/ts.php","",1,20171206\n'
                     'd,1,Payload delivery,sha256,"' + "a" * 64 + '","",1,20171206\n'
                     'e,1,Payload delivery,md5,"' + "b" * 32 + '","",1,20171206\n'
                     'f,1,Network activity,ip-dst,"10.0.0.1","",1,20171206\n')
        s = feeds.load_list(path, "misp-csv", "Citizen Lab", "Pegasus")
        got = {(i.value, i.type) for i in s.indicators}
        self.assertEqual(got, {("lure.example", TYPE_DOMAIN), ("5.6.7.8", TYPE_IP),
                               ("time-local.example", TYPE_DOMAIN), ("a" * 64, TYPE_SHA256)})
        self.assertEqual(s.sets[0]["not_applicable_to_this_scan"], {"md5": 1})
        self.assertEqual(sum(s.sets[0]["refused_invalid"].values()), 1)

    def test_citizen_lab_sources_are_allow_listed(self):
        # The count is deliberately exact. That repository also publishes
        # phishing, hack-for-hire and state-APT campaigns that are outside this
        # tool's scope, so adding one of its reports should fail here first and
        # be a reviewed decision rather than a quiet import.
        cl = [s for s in feeds.SOURCES if s["id"].startswith("citizenlab-")]
        self.assertEqual(len(cl), 6)
        for s in cl:
            self.assertTrue(feeds.url_allowed(s["url"]))
            self.assertEqual(s["format"], "misp-csv")


if __name__ == "__main__":
    unittest.main()
